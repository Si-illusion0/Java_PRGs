package conditionalstatements;

public class Ifelseprg 
{

	public static void main(String[] args) 
	{
		int a = 10, b = 15;

		if (a > b) 
		{
			System.out.println("A is greater"); // will execute when the condition is true
		} 
		else 
		{
			System.out.println("B is greater"); // will execute when the condition is false
		}

	}

}
