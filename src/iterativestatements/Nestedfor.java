package iterativestatements;

public class Nestedfor {

	public static void main(String[] args) {
		//****
		//****
		//****
		//3 rows and 4 column - 3x4 matrix
		for(int i=1;i<=3;i++)
		{
			for(int j=1;j<=4;j++) {
				System.out.print("*");
			}
			System.out.println();

		}
		
	}

}

